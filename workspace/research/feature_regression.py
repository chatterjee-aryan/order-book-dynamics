"""Daily SPY/GLD high-low regressions on four FOMC repricing channels.

Run from project root: python regress_fomc_etf_range_interactions.py
pip install pandas numpy yfinance statsmodels matplotlib

Uses the precomputed RAW daily channels generated by fomc_daily_tcm.csv.
For each channel and ETF, normalization divides by the mean of the preceding
90 VALID NON-FOMC observations, exactly as in the feature-construction script.
Blue/all-day sample includes FOMC dates; regressions include all valid days.
"""
from pathlib import Path
import numpy as np
import pandas as pd
import yfinance as yf
import statsmodels.api as sm
import matplotlib.pyplot as plt

DAILY_FILE = Path('data/processed/fomc/fomc_daily_tcm.csv')
MEETING_FILE = Path('data/processed/fomc/fomc_surprises.csv')
OUTPUT_DIR = Path('data/processed/fomc/etf_fomc_regressions')
CHANNELS = ['tcm_hl_bp', 'target_hl_bp', 'curve_slope_abs_bp', 'inflation_abs_bp']
TICKERS = ['SPY', 'GLD']
LOOKBACK = 90
HAC_LAGS = 5
CENTER = 1.0  # FOMC main effect when all normalized channels equal baseline


def prior_nonfomc_mean(series, fomc_dates, window=LOOKBACK):
    """Strictly prior 90 valid non-FOMC values; no lookahead, per channel."""
    s = pd.to_numeric(series, errors='coerce').replace([np.inf, -np.inf], np.nan)
    eligible = s.notna() & ~s.index.isin(fomc_dates)
    ordinary = s.loc[eligible]
    prev = ordinary.shift(1).rolling(window, min_periods=window).mean()
    incl = ordinary.rolling(window, min_periods=window).mean()
    mapped = incl.reindex(s.index).ffill()
    mapped.loc[eligible] = prev.reindex(mapped.index[eligible]).to_numpy()
    return mapped.where(mapped > 0)


def etf_field(raw, field):
    if isinstance(raw.columns, pd.MultiIndex):
        if field in raw.columns.get_level_values(0):
            out = raw.xs(field, axis=1, level=0)
        else:
            out = raw.xs(field, axis=1, level=1)
    else:
        raise ValueError('Expected multi-ticker yfinance columns')
    out = out.reindex(columns=TICKERS)
    idx = pd.to_datetime(out.index)
    if idx.tz is not None:
        idx = idx.tz_localize(None)
    out.index = idx.normalize()
    return out.sort_index()


def fit_model(frame, outcome, ticker, label):
    feature_cols = [f'{c}_centered' for c in CHANNELS]
    interaction_cols = [f'fomc_x_{c}' for c in CHANNELS]
    regressors = feature_cols + ['is_fomc'] + interaction_cols
    clean = frame[[outcome] + regressors].replace([np.inf, -np.inf], np.nan).dropna()
    if len(clean) < 50 or int(clean['is_fomc'].sum()) < 10:
        print(f'SKIP {ticker} {label}: insufficient complete observations')
        return None
    X = sm.add_constant(clean[regressors].astype(float), has_constant='add')
    y = clean[outcome].astype(float)
    fit = sm.OLS(y, X).fit(cov_type='HAC', cov_kwds={'maxlags': HAC_LAGS})
    # Explicit matrix tests avoid formula parsing of column names.
    def wald_test(names):
        R = np.zeros((len(names), len(fit.params)))
        for i, name in enumerate(names):
            R[i, fit.params.index.get_loc(name)] = 1.0
        test = fit.wald_test(R, scalar=True)
        return float(test.statistic), float(test.pvalue)

    interaction_stat, interaction_p = wald_test(interaction_cols)
    all_fomc_stat, all_fomc_p = wald_test(['is_fomc'] + interaction_cols)
    base = sm.OLS(y, X.drop(columns=['is_fomc'] + interaction_cols)).fit()
    print('\n' + '=' * 86)
    print(f'{ticker} | {label} | observations={len(clean)} | FOMC={int(clean.is_fomc.sum())}')
    print(f'Period: {clean.index.min().date()} to {clean.index.max().date()}')
    print(f'R² full={fit.rsquared:.4f}, adjusted={fit.rsquared_adj:.4f}, no-FOMC R²={base.rsquared:.4f}')
    print(f'Joint interactions Wald chi2(4)={interaction_stat:.3f}, p={interaction_p:.6g}')
    print(f'Joint FOMC main+interactions Wald chi2(5)={all_fomc_stat:.3f}, p={all_fomc_p:.6g}')
    print(fit.summary())

    prefix = f'{ticker.lower()}_{label}'
    (OUTPUT_DIR / f'{prefix}_summary.txt').write_text(
        f'Ticker: {ticker}\nOutcome: {label}\n'
        f'FOMC count: {int(clean.is_fomc.sum())}\n'
        f'Joint interactions Wald chi2(4): {interaction_stat:.8g}, p={interaction_p:.8g}\n'
        f'Joint main+interactions Wald chi2(5): {all_fomc_stat:.8g}, p={all_fomc_p:.8g}\n'
        f'No-FOMC R2: {base.rsquared:.8g}\n\n{fit.summary()}\n'
    )
    conf = fit.conf_int()
    coefficients = pd.DataFrame({
        'term': fit.params.index, 'estimate': fit.params.values,
        'hac_se': fit.bse.values, 't_stat': fit.tvalues.values,
        'p_value': fit.pvalues.values, 'ci_95_low': conf.iloc[:, 0].values,
        'ci_95_high': conf.iloc[:, 1].values, 'ticker': ticker,
        'outcome': label, 'n': len(clean), 'n_fomc': int(clean.is_fomc.sum()),
        'r2': fit.rsquared, 'r2_no_fomc': base.rsquared,
        'joint_interaction_p': interaction_p, 'joint_all_fomc_p': all_fomc_p,
    })
    coefficients.to_csv(OUTPUT_DIR / f'{prefix}_coefficients.csv', index=False)
    pd.DataFrame({'observed': y, 'fitted': fit.fittedvalues,
                  'residual': fit.resid, 'is_fomc': clean['is_fomc']}).to_csv(
                      OUTPUT_DIR / f'{prefix}_fitted.csv', index_label='date')
    return coefficients


def main():
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    meetings = pd.read_csv(MEETING_FILE, parse_dates=['meeting_date'])
    fomc_dates = pd.DatetimeIndex(meetings['meeting_date'].dt.normalize().dropna().unique())
    daily = pd.read_csv(DAILY_FILE, parse_dates=['date']).set_index('date').sort_index()
    daily.index = daily.index.normalize()
    if daily.index.has_duplicates:
        raise ValueError('Duplicate dates in daily data')
    for channel in CHANNELS:
        if channel not in daily.columns:
            raise ValueError(f'Missing {channel} in daily raw dataset; rerun original construction script')
        raw = pd.to_numeric(daily[channel], errors='coerce').replace([np.inf, -np.inf], np.nan)
        raw = raw.where(raw >= 0)
        daily[f'{channel}_normalized'] = raw / prior_nonfomc_mean(raw, fomc_dates)
        daily[f'{channel}_centered'] = daily[f'{channel}_normalized'] - CENTER

    # Verify parity against original FOMC-only normalized values (if present).
    print('\nNORMALIZATION PARITY CHECK (against original fomc_surprises.csv)')
    for channel in CHANNELS:
        name = f'{channel}_normalized'
        if name not in meetings:
            continue
        original = meetings.set_index('meeting_date')[name]
        new = daily[name].reindex(original.index)
        valid = original.notna() & new.notna()
        if valid.any():
            diffs = (original[valid] - new[valid]).abs()
            print(f'{channel}: matched={valid.sum()}, max_abs_diff={diffs.max():.3g}, '
                  f'count_diff_gt_1e-8={(diffs > 1e-8).sum()}')
            if (diffs > 1e-8).any():
                print('WARNING: feature normalization does not match original meeting data!')

    start = (daily.index.min() - pd.Timedelta(days=260)).strftime('%Y-%m-%d')
    end = (daily.index.max() + pd.Timedelta(days=8)).strftime('%Y-%m-%d')
    raw_etf = yf.download(TICKERS, start=start, end=end, auto_adjust=True,
                          actions=False, progress=False, threads=False)
    if raw_etf.empty:
        raise RuntimeError('No ETF data from yfinance')
    high, low = etf_field(raw_etf, 'High'), etf_field(raw_etf, 'Low')
    ranges = (high - low).where((high >= low) & (low > 0))
    for ticker in TICKERS:
        daily[f'{ticker}_range_dollars'] = ranges[ticker].reindex(daily.index)
        excess = ranges[ticker] / prior_nonfomc_mean(ranges[ticker], fomc_dates)
        daily[f'{ticker}_excess_range'] = excess.reindex(daily.index)

    daily['is_fomc'] = daily.index.isin(fomc_dates).astype(int)
    for channel in CHANNELS:
        daily[f'fomc_x_{channel}'] = daily['is_fomc'] * daily[f'{channel}_centered']
    daily.to_csv(OUTPUT_DIR / 'regression_daily_data.csv', index_label='date')

    all_results = []
    for ticker in TICKERS:
        # Raw adjusted high-low as explicitly requested, plus volatility-scaled robustness.
        for outcome, label in [(f'{ticker}_range_dollars', 'raw_range'),
                               (f'{ticker}_excess_range', 'excess_range')]:
            result = fit_model(daily, outcome, ticker, label)
            if result is not None:
                all_results.append(result)
    if all_results:
        pd.concat(all_results, ignore_index=True).to_csv(
            OUTPUT_DIR / 'all_coefficients.csv', index=False)
    print('\nSaved results in:', OUTPUT_DIR)


if __name__ == '__main__':
    main()
